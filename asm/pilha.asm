@ /0500
SUB_PUSH K /0000
 JP PUSH_BODY
PUSH_ARG K /0000
PUSH_ERROR_SLOT JP PUSH_FAIL
PUSH_STATUS K /0000
PUSH_BODY LD STACK_POINTER
 - STACK_BASE
 JZ PUSH_ERROR_SLOT
 LD ZERO
 MM PUSH_STATUS
 LD STACK_POINTER
 - TWO
 MM STACK_POINTER
 + STORE_OPCODE
 MM PUSH_STORE
 LD PUSH_ARG
PUSH_STORE K /9000
 RS SUB_PUSH
PUSH_FAIL LD ONE
 MM PUSH_STATUS
 RS SUB_PUSH

@ /0700
SUB_POP K /0000
 JP POP_BODY
POP_RESULT K /0000
POP_ERROR_SLOT JP POP_FAIL
POP_STATUS K /0000
POP_BODY LD STACK_POINTER
 - STACK_EMPTY
 JZ POP_ERROR_SLOT
 LD ZERO
 MM POP_STATUS
 LD STACK_POINTER
 + LOAD_OPCODE
 MM POP_LOAD
POP_LOAD K /8000
 MM POP_RESULT
 LD STACK_POINTER
 + TWO
 MM STACK_POINTER
 RS SUB_POP
POP_FAIL LD ONE
 MM POP_STATUS
 RS SUB_POP

@ /0E00
ZERO K /0000
ONE K /0001
TWO K /0002
TEN K /000A
STACK_BASE K /0F00
STACK_EMPTY K /0FFE
STORE_OPCODE K /9000
LOAD_OPCODE K /8000
@ /0FFE
STACK_POINTER K /0FFE
